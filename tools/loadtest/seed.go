package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"regexp"
	"time"
)

var (
	uuidPattern = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)
	keyPattern  = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,62}$`)
)

// cmdSeedSQL writes one transaction that creates users, their memberships in an existing
// workspace and one session each, and appends the sessions to an accounts file. Creating
// thousands of accounts through email codes would take far longer than the test itself;
// the rows are the ones the API writes (see internal/auth and migrations 00001–00004):
// sessions store SHA-256(token), and the memberships trigger joins the default channel.
func cmdSeedSQL(args []string) error {
	fs := flag.NewFlagSet("seed-sql", flag.ExitOnError)
	orgID := fs.String("org", "", "workspace (organization) ID")
	role := fs.String("role", "employee", "key of the role the new members get")
	users := fs.Int("users", 50, "number of users to create")
	start := fs.Int("start", 1, "number of the first user (emails load-00001@…)")
	prefix := fs.String("prefix", "load", "email local-part prefix")
	domain := fs.String("domain", "loadtest.example", "email domain")
	ttl := fs.Duration("session-ttl", 24*time.Hour, "session lifetime")
	sqlPath := fs.String("sql", "", "output SQL file")
	tokensPath := fs.String("tokens", "", "accounts file the new sessions are appended to (mode 0600)")
	_ = fs.Parse(args)

	switch {
	case !uuidPattern.MatchString(*orgID):
		return errors.New("seed-sql: -org must be a workspace UUID")
	case !keyPattern.MatchString(*role):
		return errors.New("seed-sql: -role must be a role key such as employee")
	case !keyPattern.MatchString(*prefix) || !regexp.MustCompile(`^[a-z0-9.-]+\.[a-z]{2,63}$`).MatchString(*domain):
		return errors.New("seed-sql: -prefix and -domain must be lower-case email parts")
	case *users < 1 || *start < 1:
		return errors.New("seed-sql: -users and -start must be positive")
	case *sqlPath == "" || *tokensPath == "":
		return errors.New("seed-sql: -sql and -tokens are required")
	}

	accs := make([]account, *users)
	hashes := make([]string, *users)
	names := make([]string, *users)
	for i := range accs {
		n := *start + i
		token, hash := newSessionToken()
		accs[i] = account{UserID: newUUIDv7(), Email: fmt.Sprintf("%s-%05d@%s", *prefix, n, *domain), Token: token}
		hashes[i] = hash
		names[i] = fmt.Sprintf("Load User %05d", n)
	}

	f, err := os.OpenFile(*sqlPath, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return err
	}
	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "-- Generated by tools/loadtest seed-sql: %d users in workspace %s.\nBEGIN;\n", *users, *orgID)
	fmt.Fprintf(w, `DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM roles WHERE org_id = '%s' AND key = '%s') THEN
    RAISE EXCEPTION 'role %s not found in workspace %s';
  END IF;
END $$;
`, *orgID, *role, *role, *orgID)
	w.WriteString("INSERT INTO users (id, email, display_name, locale) VALUES\n")
	for i, a := range accs {
		fmt.Fprintf(w, "  ('%s', '%s', '%s', 'en')%s\n", a.UserID, a.Email, names[i], sep(i, len(accs)))
	}
	w.WriteString("INSERT INTO memberships (org_id, user_id, role_id)\n")
	fmt.Fprintf(w, "SELECT '%s', u.id, r.id FROM roles r CROSS JOIN (VALUES\n", *orgID)
	for i, a := range accs {
		fmt.Fprintf(w, "  ('%s'::uuid)%s\n", a.UserID, sepTail(i, len(accs), ""))
	}
	fmt.Fprintf(w, ") AS u(id) WHERE r.org_id = '%s' AND r.key = '%s';\n", *orgID, *role)
	w.WriteString("INSERT INTO sessions (id, user_id, token_hash, user_agent, expires_at) VALUES\n")
	for i, a := range accs {
		fmt.Fprintf(w, "  ('%s', '%s', decode('%s', 'hex'), 'fudislte-loadtest', now() + interval '%d seconds')%s\n",
			newUUIDv7(), a.UserID, hashes[i], int64(ttl.Seconds()), sep(i, len(accs)))
	}
	w.WriteString("COMMIT;\n")
	if err := w.Flush(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := writeAccounts(*tokensPath, accs, true); err != nil {
		return err
	}
	fmt.Printf("seed-sql: %d users written to %s, sessions appended to %s\n", *users, *sqlPath, *tokensPath)
	return nil
}

// sep ends a VALUES row: a comma, or a semicolon after the last one.
func sep(i, n int) string {
	if i == n-1 {
		return ";"
	}
	return ","
}

// sepTail is sep for a VALUES list that is followed by more SQL.
func sepTail(i, n int, last string) string {
	if i == n-1 {
		return last
	}
	return ","
}
